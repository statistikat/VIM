if (!all(vapply(c("mlr3", "mlr3learners", "mlr3pipelines", "mlr3tuning",
                 "paradox", "R6", "future"), requireNamespace, logical(1), quietly = TRUE)))
  exit_file("mlr3 stack not installed")
if (!at_home()) exit_file("benchmark integration runs at home")
library(VIM)
paths <- file.path(c(".", "..", "../.."), "dev-notes", "benchmarks", "tabicl2.R")
paths <- paths[file.exists(paths)]
if (!length(paths)) exit_file("development benchmark files not available")
e <- new.env()
sys.source(paths[1], e)
sys.source(file.path(dirname(paths[1]), "tabicl2-refresh.R"), e)
base <- tempfile(); dir.create(base)
src <- file.path(base, "old"); dst <- file.path(base, "new")
dir.create(src); dir.create(file.path(src, "n60"))
cfg <- e$uci_config(); cfg$n <- 60L; cfg$repetitions <- 1L
cfg$mechanisms <- "MCAR"; cfg$rates <- .2
cfg$methods <- c("kNN", "kNN_rf", "cellwise", "cellwise_seq10", "ranger")
old <- cfg; old$methods <- c("kNN", "ranger")
set.seed(81)
truth <- data.frame(age = rnorm(60), hours_per_week = rnorm(60),
                    income = factor(rep(c("a", "b"), 30)))
d <- makeMissing(truth, vars = c("hours_per_week", "income"), prop = .2, seed = 2)
mask <- attr(d, "where")
meta <- data.frame(dataset = "Adult", repetition = 1L, mechanism = "MCAR", rate = .2,
  method = old$methods, sample_seed = 1L, seed = 2L, model_seed = 1002L,
  elapsed = .5, status = "ok", error = "", warnings = "")
scores <- e$uci_score(truth, truth, mask, c("hours_per_week", "income"))
metrics <- do.call(rbind, lapply(1:2, function(i)
  cbind(meta[rep(i, nrow(scores)), ], scores)))
a <- list("Adult-1-MCAR-0.2" = list(truth = truth, row_ids = 1:60,
  mask = mask, completed = list(kNN = truth, ranger = truth)))
saveRDS(old, file.path(src, "config.rds"))
p <- file.path(src, "n60")
saveRDS(old, file.path(p, "config.rds")); saveRDS(old, file.path(p, "complete.rds"))
saveRDS(a, file.path(p, "artifacts.rds"))
write.csv(meta, file.path(p, "runs.csv"), row.names = FALSE)
write.csv(metrics, file.path(p, "metrics.csv"), row.names = FALSE)
for (f in c("preprocessing.csv", "sources.csv"))
  write.csv(data.frame(fixture = TRUE), file.path(p, f), row.names = FALSE)
writeLines("fixture", file.path(p, "session.txt"))
source_files <- list.files(src, full.names = TRUE, recursive = TRUE)
before <- tools::md5sum(source_files)
e$uci_refresh_methods(src, dst, cfg)
runs <- read.csv(file.path(dst, "runs.csv"))
expect_equal(nrow(runs), 5L)
expect_true(all(runs$status == "ok"))
expect_equal(runs$elapsed[runs$method == "ranger"], .5)
expect_identical(readRDS(file.path(dst, "n60", "artifacts.rds"))[[1]]$completed$ranger, truth)
expect_identical(tools::md5sum(source_files), before)
checkpoint <- file.path(dst, "n60", "refresh-checkpoint.rds")
cp_hash <- tools::md5sum(checkpoint)
e$uci_refresh_methods(src, dst, cfg)
expect_identical(tools::md5sum(checkpoint), cp_hash)
expect_error(e$uci_refresh_methods(src, src, cfg), "separate")
bad <- cfg; bad$seed <- 9L
expect_error(e$uci_refresh_methods(src, tempfile(), bad), "configuration differs")
unlink(base, recursive = TRUE)
