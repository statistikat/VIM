library(VIM)
if (identical(Sys.getenv("VIM_RUN_TRANSFORMER_TESTS"), "true")) {
  tf <- tensorflow::tf; layers <- VIM:::.transformer_layers()
  values <- tf$constant(array(c(2,4,100,100), dim=c(1L,2L,2L)), dtype=tf$float32)
  tokens <- tf$constant(matrix(c(1L,0L),1), dtype=tf$int32)
  pooled <- as.array(layers$MaskedMean()(list(values,tokens)))
  expect_equal(as.numeric(pooled), c(2,100))
  empty <- tf$zeros_like(tokens)
  expect_equal(as.numeric(as.array(layers$MaskedMean()(list(values,empty)))), c(0,0))
  model <- VIM:::build_model_cLM(5L, 16L, 4L, 32L, 1L, 5L, 10L, 0, 8L, 3L,
                                head_dim="compact", pooling="masked")
  left <- matrix(c(0,0,1,2,3),1); right <- matrix(c(1,2,3,0,0),1)
  expect_equal(predict(model,left,verbose=0L), predict(model,right,verbose=0L), tolerance=1e-5)
  expect_true(all(is.finite(predict(model,matrix(0,1,5),verbose=0L))))
  keras::compile(model, optimizer="adam",loss="sparse_categorical_crossentropy")
  keras::fit(model, rbind(left,right), c(0,1), epochs=1L,verbose=0L)
  expect_true(all(is.finite(predict(model,left,verbose=0L))))
  path <- tempfile(); keras::save_model_tf(model,path)
  restored <- keras::load_model_tf(path)
  expect_equal(predict(model,left,verbose=0L), predict(restored,left,verbose=0L))
  unlink(path,recursive=TRUE)
}
# Decoder must not allocate R objects or draw from the R RNG in worker threads.
tokens <- data.frame(TOKEN=1:2, Word_ngram=c("a","b"))
prob <- matrix(rep(c(.1,.9), 500), ncol=2, byrow=TRUE)
out <- VIM:::parallel_tokenpred_to_string(prob, tokens, FALSE)
expect_identical(length(out), 500L)
expect_true(all(vapply(out,function(x) x$token == "b",logical(1))))
set.seed(1); a <- VIM:::parallel_tokenpred_to_string(prob,tokens,TRUE)
set.seed(1); b <- VIM:::parallel_tokenpred_to_string(prob,tokens,TRUE)
expect_identical(a,b)
expect_error(VIM:::parallel_tokenpred_to_string(matrix(c(NA,1),1),tokens,FALSE))
